#!/usr/bin/env python3
"""Run the built Spatial face inside an installed DeepSeek Harness (dsh 0.2.1-alpha.5) and print the URL.

The face is built by `build-face.py` (it leaves `<name>/lib/index.js` and `<name>/lib/client.js` beside each
package). This script assembles a runtime copy of the nine packages beside a composition patch and boots
`dsh web` with that patch, so the harness's own frame, thread lane and workspace browser are replaced by the face's
(the same four rows Prime disabled: ui-layout, ui-sidebar, ui-workspace, ui-settings-general).

Everything it writes goes under `--install` (a scratch folder holding `npm install @deepseek-ai/dsh@0.2.1-alpha.5`),
including DSH_HOME, so nothing lands in the user's own ~/.dsh.

Usage:
    python3 preview-face.py --install ~/face-scratch-dsh [--port 3099] [--no-start]
"""
import argparse, json, os, re, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FOUNDATION = HERE.parent / 'aukora-foundation'
FACES = ('layout', 'sidebar', 'threads', 'apps', 'messages', 'documents', 'aumlok', 'settings', 'memory')
CARRY = ('assets', 'vendor', 'package.json')

# The four upstream rows the face replaces. Our module ids differ from the upstream package names on purpose:
# identical ids are refused at composition as resolving from multiple active loader sources.
REPLACED = ('ui-layout', 'ui-settings-general', 'ui-sidebar', 'ui-workspace')


def assemble(install: Path) -> Path:
    """Write the `aukora` profile: dsh-base, then one face bundle that is dsh-web-app's patch with the four replaced
    rows removed and the face's rows added. Returns the profile directory.

    WHY THE ROWS ARE REMOVED, NOT DISABLED. Settings namespaces are plugin entry ids in DSH 0.2.1-alpha.5, and the
    harness's own welcome notice (ui-settings-models) writes `welcomeNoticeVersion` into the Config of the entry named
    `ui-settings-general`. The config editor refuses an id that two entries share, and a disabled row is still an
    entry, so the face's settings host plugin can only take that id if the upstream row is not there at all.
    """
    web = install / 'node_modules/@deepseek-ai/dsh-web-app'
    manifest = json.loads((web / 'package.json').read_text())
    patches = manifest['dsh']['bundle']['patch']
    patches = [patches] if isinstance(patches, str) else patches
    profile = install / 'home/profiles/aukora'
    bundle = profile / 'node_modules/@aukora/face-bundle'
    if bundle.exists():
        shutil.rmtree(bundle)
    bundle.mkdir(parents=True)
    for rel in patches:
        target = bundle / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(web / rel, target)
    main_patch = bundle / patches[0]
    text = main_patch.read_text()
    for row in REPLACED:
        text, count = re.subn(r"^    - id: %s\n      name: [^\n]+\n\n?" % re.escape(row), '', text, flags=re.M)
        if count != 1:
            sys.exit(f'web-bundle-drift: expected exactly one `{row}` row in dsh-web-app, found {count}')

    for name in FACES:
        src, dst = HERE / name, bundle / 'aukora-face' / name
        if not (src / 'lib/client.js').is_file():
            sys.exit(f'face-not-built: {name} (run build-face.py first)')
        (dst / 'lib').mkdir(parents=True)
        for item in ('index.js', 'client.js'):
            if (src / 'lib' / item).is_file():
                shutil.copy2(src / 'lib' / item, dst / 'lib' / item)
        for item in CARRY:
            if (src / item).is_dir():
                shutil.copytree(src / item, dst / item)
            elif (src / item).is_file():
                shutil.copy2(src / item, dst / item)
    if not (FOUNDATION / 'lib/client.js').is_file():
        sys.exit('foundation-not-built: run build-face.py first')
    (bundle / 'aukora-foundation/lib').mkdir(parents=True)
    for item in ('index.js', 'client.js'):
        shutil.copy2(FOUNDATION / 'lib' / item, bundle / 'aukora-foundation/lib' / item)
    shutil.copy2(FOUNDATION / 'package.json', bundle / 'aukora-foundation/package.json')

    # The settings face takes the replaced upstream row's id (see above).
    ids = {'settings': 'ui-settings-general'}
    # PETER'S ORDER, 2026-09-27 (kept from Prime's layout/index.ts): no first-run form opens by itself; the model key lives
    # in the Models tab. DSH 0.2.1-alpha.5 added a "Get started" sign-in dialog to ui-settings-models, switched by this key.
    text += '\n# No first-run form opens by itself.\n- id: ui-settings-models\n  config:\n    credentialOnboarding: false\n'
    text += '\n# THE FACE (generated by preview-face.py).\n- insert:\n    - id: aukora-foundation\n      name: ./aukora-foundation/lib/index.js\n' + ''.join(
        f'    - id: {ids.get(name, "aukora-face-" + name)}\n      name: ./aukora-face/{name}/lib/index.js\n'
        for name in FACES)
    # DISABLED IN SOVEREIGN (PORT-NOTES.md, "Disabled in Sovereign"): the engine holds no keys and runs no program, so the
    # copied switches that would reach out are set off here and the copied source is left as it is. Voice (the WebSocket
    # bridge and the Python sidecar) is not carried at all. The model-provider route has no address and no consent.
    text += (
        '\n# Sovereign: no provider, no repo or web lens, no weights script, no organism reader, no voice.\n'
        '- id: aukora-face-apps\n  config:\n'
        '    providerSendConsent: false\n    voiceEnabled: false\n    voiceAutoStart: false\n'
        "    repoLensRoot: ''\n    repoLensLookups: 0\n    webLensLookups: 0\n"
        "    weightsControlScript: ''\n    organismDshHome: ''\n    organismRepo: ''\n")
    main_patch.write_text(text)
    (bundle / 'package.json').write_text(json.dumps({
        'name': '@aukora/face-bundle', 'version': '0.0.0', 'private': True,
        'dsh': {'bundle': {'patch': patches}},
    }) + '\n')

    profile.mkdir(parents=True, exist_ok=True)
    (profile / 'cordis.yml').write_text('[]\n')
    # The profile's own patch is the user's: dsh writes setting changes (the welcome acknowledgement) there, so keep it.
    if not (profile / 'cordis.patch.yml').exists():
        (profile / 'cordis.patch.yml').write_text('[]\n')
    (profile / 'pnpm-workspace.yaml').write_text('packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n')
    (profile / 'package.json').write_text(json.dumps({
        'name': 'dsh-profile-aukora', 'private': True, 'dependencies': {},
        'dsh': {'profile': {'bundles': ['@deepseek-ai/dsh-base', '@aukora/face-bundle']}},
    }) + '\n')
    return profile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--install', type=Path, required=True)
    parser.add_argument('--port', type=int, default=3099)
    parser.add_argument('--no-start', action='store_true')
    a = parser.parse_args()
    install = a.install.expanduser().resolve()
    dsh = install / 'node_modules/.bin/dsh'
    if not dsh.is_file():
        sys.exit(f'dsh-not-installed: {dsh}')
    profile = assemble(install)
    print(f'profile: {profile}')
    if a.no_start:
        return
    env = dict(os.environ, DSH_HOME=str(install / 'home'))
    os.execve(str(dsh), [str(dsh), '--profile', 'aukora', '--no-open', '--port', str(a.port)], env)


if __name__ == '__main__':
    main()
