//! Version 1 definitions of all private checks and paired corner observations.

use crate::health::{CheckDefinition, CheckId, CornerDefinition, CornerId, OrganId};

/// Creates a fixed private definition; the id constructor checks 1..=18.
const fn check(
    owner: OrganId,
    index: u8,
    invariant: &'static str,
    source: &'static str,
    freshness_limit_ms: u64,
) -> CheckDefinition {
    CheckDefinition {
        id: CheckId::fixed(owner, index),
        owner,
        invariant,
        source,
        freshness_limit_ms,
    }
}

/// Creates a fixed paired definition; the id constructor checks 1..=20.
const fn corner(
    index: u8,
    organ_pair: &'static str,
    owners: [OrganId; 2],
    invariant: &'static str,
    sources: [&'static str; 2],
    freshness_limit_ms: u64,
) -> CornerDefinition {
    CornerDefinition {
        id: CornerId::fixed(index),
        organ_pair,
        owners,
        invariant,
        sources,
        freshness_limit_ms,
    }
}

