use super::*;

macro_rules! registry {
    ($( $name:ident ),+ $(,)?) => {
        /// All refusal codes recognized by this version of the shared spine.
        pub const ALL: &[Refusal] = &{
            let core = [$($name),+];
            let mut entries = [FRAME_INVALID_FIELD; [$($name),+].len()
                + COPRESENCE_CODES.len() + LAUNCHER_CODES.len() + ORGAN_CODES.len()];
            let mut index = 0;
            while index < core.len() {
                entries[index] = core[index];
                index += 1;
            }
            let mut extra = 0;
            while extra < COPRESENCE_CODES.len() {
                entries[index + extra] = COPRESENCE_CODES[extra];
                extra += 1;
            }
            index += extra;
            extra = 0;
            while extra < LAUNCHER_CODES.len() {
                entries[index + extra] = LAUNCHER_CODES[extra];
                extra += 1;
            }
            index += extra;
            extra = 0;
            while extra < ORGAN_CODES.len() {
                entries[index + extra] = ORGAN_CODES[extra];
                extra += 1;
            }
            entries
        };
    };
}

macro_rules! combine_codes {
    ($( $group:expr ),+ $(,)?) => {
        &{
            let groups = [$($group),+];
            let mut entries = [FRAME_INVALID_FIELD; 0 $(+ $group.len())+];
            let mut index = 0;
            let mut group = 0;
            while group < groups.len() {
                let mut extra = 0;
                while extra < groups[group].len() {
                    entries[index + extra] = groups[group][extra];
                    extra += 1;
                }
                index += extra;
                group += 1;
            }
            entries
        }
    };
}

