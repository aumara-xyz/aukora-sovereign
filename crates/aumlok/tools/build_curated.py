#!/usr/bin/env python3
"""Validate the reviewed phrase lists in data/curated/ and measure the drawn distribution.

The curated lists are the only lists phrases are drawn from. Theme words ship unchanged;
anchors ship after the threshold that maximizes exact min-entropy (build_lists.optimize_anchors).
`--check` refuses drift between the reviewed sources and every shipped artifact.
"""
import argparse
from decimal import Decimal, localcontext
import hashlib
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_lists import SLOTS, anchor_profile, floor_bits, optimize_anchors  # noqa: E402

CRATE = Path(__file__).resolve().parents[1]
THEMES = ['ROOT', 'UNITE', 'RISE']
THEME_WORD = re.compile(r'[a-z]{3,12}\Z')
ANCHOR_WORD = re.compile(r'[a-z]{6}\Z')
# A hard backstop only: a curated word on either list stops the build for human review.
BLOCKING = ['safety/profanity-block.json', 'safety/ldnoobw-en.txt']


def read_list(name):
    raw = (CRATE / 'data/curated' / name).read_bytes()
    text = raw.decode('ascii')
    if not text.endswith('\n') or '\r' in text:
        raise ValueError(f'aumlok:curated-format: {name}')
    return text.splitlines(), hashlib.sha256(raw).hexdigest()


def validate(themes, candidates):
    errors = []
    blocked = json.loads((CRATE / 'vectors/legacy/sources.json').read_text())['words']
    blocking = set().union(*(set(blocked[name]) for name in BLOCKING))
    for name, words, shape in [(t, themes[t], THEME_WORD) for t in THEMES] + [('ANCHORS', candidates, ANCHOR_WORD)]:
        errors += [f'{name}: bad shape {w!r}' for w in words if not shape.fullmatch(w)]
        errors += [f'{name}: not sorted/unique at {a!r},{b!r}' for a, b in zip(words, words[1:]) if a >= b]
        errors += [f'{name}: blocked word {w!r}' for w in words if w in blocking]
        if name != 'ANCHORS':
            # Within one first-letter bucket no word is a prefix of another.
            errors += [f'{name}: prefix collision {a!r} < {b!r}' for a, b in zip(words, words[1:]) if b.startswith(a)]
    if errors:
        raise SystemExit('aumlok:curated-invalid\n' + '\n'.join(errors))


def artifacts():
    themes, hashes = {}, {}
    for theme in THEMES:
        themes[theme], hashes[f'curated/{theme}.txt'] = read_list(f'{theme}.txt')
    candidates, hashes['curated/ANCHOR-CANDIDATES.txt'] = read_list('ANCHOR-CANDIDATES.txt')
    validate(themes, candidates)
    anchors, measurement, curve = optimize_anchors({t: set(ws) for t, ws in themes.items()}, set(candidates))
    outputs = {f'data/{theme}.txt': ''.join(w + '\n' for w in words) for theme, words in themes.items()}
    outputs['data/ANCHORS.txt'] = ''.join(a + '\n' for a in sorted(anchors))
    outputs['vectors/entropy.json'] = json.dumps(measurement, sort_keys=True, separators=(',', ':')) + '\n'
    outputs['vectors/threshold-curve.json'] = json.dumps(curve, sort_keys=True, separators=(',', ':')) + '\n'
    outputs['src/entropy_constants.rs'] = '\n'.join([
        '// Generated by tools/build_curated.py from the curated lists.',
        f'pub const ANCHOR_THRESHOLD: usize = {measurement["anchor_threshold"]};',
        f'pub const ANCHOR_COUNT: usize = {measurement["anchor_count"]};',
        f'pub const WEAKEST_ANCHOR: &str = "{measurement["weakest_anchor"]}";',
        f'pub const MIN_PROBABILITY_DENOMINATOR: u128 = {measurement["min_probability_denominator"]};',
        f'pub const MIN_ENTROPY_BITS: f64 = {measurement["min_entropy_float"]!r};',
        f'pub const AVERAGE_ENTROPY_BITS: f64 = {measurement["average_entropy_float"]!r};',
        f'pub const MIN_ENTROPY_DISPLAY: &str = "{measurement["min_entropy_bits"]}";',
        f'pub const AVERAGE_ENTROPY_DISPLAY: &str = "{measurement["average_entropy_bits"]}";', ''])
    with localcontext() as context:
        context.prec = 110
        ln2 = Decimal(2).ln()
        outputs['vectors/anchor-entropy.tsv'] = 'anchor\tROOT1\tROOT2\tUNITE1\tUNITE2\tRISE1\tRISE2\tbits (floored)\n' + ''.join(
            anchor + '\t' + '\t'.join(str(measurement['buckets'][t][letter]) for t, letter in zip(SLOTS, anchor)) + '\t'
            + floor_bits(Decimal(len(anchors) * anchor_profile(measurement['buckets'], anchor)[1]).ln() / ln2) + '\n'
            for anchor in sorted(anchors))
    counts = measurement['buckets']
    provenance = [
        '# Phrase list provenance', '',
        'New phrases are drawn only from these curated lists. They were reviewed on 2026-10-14 to be',
        'common everyday words that are positive or pleasant and on theme, after the earlier lists drew',
        'morbid and obscure words. Each word was kept from the legacy (v1) lists or added from',
        '`/usr/share/dict/words` (Webster\'s Second, public domain); a few modern space and technology',
        'words absent from that 1934 dictionary are listed in `curated/README.md`. No spelling is invented.', '',
        '- ROOT (words 2-3) = nature: plants, animals, land, water, weather, gems, natural light.',
        '- UNITE (words 4-5) = people, connection and celebration.',
        '- RISE (words 6-7) = spirit, space and technology.',
        '- Anchors (word 1) are six-letter everyday words; words 2-7 start with its letters in order.', '',
        'Rules (checked by `tools/build_curated.py`): lowercase a-z; theme words 3-12 letters, anchors',
        'exactly 6; sorted and unique; no word is a prefix of another in its theme and first-letter',
        'bucket; no word on the profanity or LDNOOBW lists. The legacy lists in `legacy/` are accepted',
        'when an existing phrase is typed and are never drawn.', '',
        '## Bucket sizes', '',
        '| Letter | ' + ' | '.join(THEMES) + ' |', '| --- | ' + ' | '.join('---:' for _ in THEMES) + ' |']
    provenance += [f'| {letter} | ' + ' | '.join(str(counts[t][letter]) for t in THEMES) + ' |'
                   for letter in 'abcdefghijklmnopqrstuvwxyz']
    provenance += [
        '', '## Entropy', '',
        'For anchor a, P(a) is the product of its six slot bucket sizes in ROOT, ROOT, UNITE, UNITE,',
        'RISE, RISE order. Every phrase under a has probability 1/(N*P(a)), so the exact minimum',
        'entropy is log2(N*min P(a)); the average is log2(N) + (1/N)*sum_a log2(P(a)). An anchor is',
        'kept only if all six of its buckets reach the threshold T that maximizes N*min P(a).', '',
        f'Counts: ROOT={len(themes["ROOT"])}, UNITE={len(themes["UNITE"])}, RISE={len(themes["RISE"])}, '
        f'anchor candidates={len(candidates)}, anchors drawn={len(anchors)} (T={measurement["anchor_threshold"]}).',
        f'Weakest anchor: `{measurement["weakest_anchor"]}`; slot buckets {measurement["weakest_buckets"]}.',
        f'Minimum: {measurement["min_entropy_bits"]} bits. Average: {measurement["average_entropy_bits"]} bits.', '',
        '## Source hashes', '', '| Curated source | SHA-256 |', '| --- | --- |']
    provenance += [f'| `{name}` | `{digest}` |' for name, digest in sorted(hashes.items())]
    outputs['data/PROVENANCE.md'] = '\n'.join(provenance) + '\n'
    return outputs, measurement


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, measurement = artifacts()
    for name, content in outputs.items():
        path = CRATE / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('aumlok:data-drift: ' + name)
        else:
            path.write_text(content, encoding='utf8')
    print(json.dumps({k: v for k, v in measurement.items() if k != 'buckets'}, sort_keys=True))


if __name__ == '__main__':
    main()
