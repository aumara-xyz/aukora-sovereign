//! Serves ui/owner exactly as written: every file except the dev server, the tests and
//! reports becomes one static asset, so a new screen can never be left out.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn walk(root: &Path, dir: &Path, out: &mut Vec<PathBuf>) {
    let mut entries: Vec<_> = std::fs::read_dir(dir)
        .expect("ui/owner is readable")
        .map(|entry| entry.expect("ui/owner entry").path())
        .collect();
    entries.sort();
    for path in entries {
        let relative = path.strip_prefix(root).unwrap();
        let first = relative.components().next().unwrap().as_os_str();
        if first == "dev" || first == "test" {
            continue;
        }
        if path.is_dir() {
            walk(root, &path, out);
        } else if matches!(
            path.extension().and_then(|e| e.to_str()),
            Some("js" | "css" | "html" | "svg" | "json")
        ) {
            out.push(path);
        }
    }
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("../../ui/owner");
    // A file has no children: this missing watch forces enumeration of the current checkout.
    println!("cargo:rerun-if-changed=build.rs/.checkout");
    println!("cargo:rerun-if-changed=../../ui/owner");
    let mut files = Vec::new();
    walk(&root, &root, &mut files);
    let mut table = String::from("// Generated by build.rs from ui/owner.\n&[\n");
    for path in &files {
        let relative = path
            .strip_prefix(&root)
            .unwrap()
            .to_str()
            .unwrap()
            .replace('\\', "/");
        println!("cargo:rerun-if-changed=../../ui/owner/{relative}");
        let mime = match path.extension().and_then(|e| e.to_str()).unwrap() {
            "js" => "text/javascript; charset=utf-8",
            "css" => "text/css; charset=utf-8",
            "html" => "text/html; charset=utf-8",
            "svg" => "image/svg+xml",
            _ => "application/json",
        };
        writeln!(
            table,
            "    ({:?}, {:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {:?}))),",
            format!("/{relative}"),
            mime,
            format!("/../../ui/owner/{relative}")
        )
        .unwrap();
    }
    table.push_str("]\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("owner_assets.rs");
    if !std::fs::read(&out).is_ok_and(|existing| existing == table.as_bytes()) {
        std::fs::write(out, table).unwrap();
    }
}
